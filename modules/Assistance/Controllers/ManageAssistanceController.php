{
    protected $assistanceClass;
    protected $assistanceTranslationClass;
    protected $assistanceTermClass;
    protected $attributesClass;
    protected $locationClass;
    protected $bookingClass;
    protected $enquiryClass;

    public function __construct(Assistance $assistanceClass, AssistanceTranslation $assistanceTranslationClass, AssistanceTerm $assistanceTermClass, Attributes $attributesClass, Location $locationClass, Booking $bookingClass, Enquiry $enquiryClass)
    {
        parent::__construct();
        $this->assistanceClass = $assistanceClass;
        $this->assistanceTranslationClass = $assistanceTranslationClass;
        $this->attributesClass = $attributesClass;
        $this->assistanceTermClass = $assistanceTermClass;
        $this->locationClass = $locationClass;
        $this->bookingClass = $bookingClass;
        $this->enquiryClass = $enquiryClass;
    }

    public function callAction($method, $parameters)
    {
        if(!$this->assistanceClass::isEnable())
        {
            return redirect('/');
        }
        return parent::callAction($method, $parameters); // TODO: Change the autogenerated stub
    }
    public function manageAssistance(Request $request)
    {
        $this->checkPermission('assistance_view');
        $user_id = Auth::id();
        $list_tour = $this->assistanceClass::where("author_id", $user_id)->orderBy('id', 'desc');
        $data = [
            'rows' => $list_tour->paginate(5),
            'breadcrumbs'        => [
                [
                    'name' => __('Gerenciar Serviços'),
                    'url'  => route('assistance.vendor.index')
                ],
                [
                    'name'  => __('Todos'),
                    'class' => 'active'
                ],
            ],
            'page_title'         => __("Gerenciar Serviços"),
        ];
        return view('Assistance::frontend.manageAssistance.index', $data);
    }

    public function recovery(Request $request)
    {
