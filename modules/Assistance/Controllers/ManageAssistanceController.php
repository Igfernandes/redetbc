<?php
namespace Modules\Assistance\Controllers;

use Modules\Booking\Events\BookingUpdatedEvent;
use Modules\Core\Events\CreatedServicesEvent;
use Modules\FrontendController;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Modules\Location\Models\LocationCategory;
use Modules\Assistance\Hook;
use Modules\Assistance\Models\Assistance;
use Modules\Assistance\Models\AssistanceCategory;
use Modules\Assistance\Models\AssistanceTranslation;
use Modules\Location\Models\Location;
use Modules\Core\Models\Attributes;
use Modules\Assistance\Models\AssistanceTerm;
use Modules\Booking\Models\Booking;

class ManageAssistanceController extends FrontendController
{
    protected $assistanceClass;
    protected $assistanceTranslationClass;
    protected $assistanceCategoryClass;
    protected $assistanceTermClass;
    protected $attributesClass;
    protected $locationClass;
    protected $bookingClass;
    /**
     * @var string
     */
    private $locationCategoryClass;

    public function __construct()
    {
        $this->assistanceClass = Assistance::class;
        $this->assistanceTranslationClass = AssistanceTranslation::class;
        $this->assistanceCategoryClass = AssistanceCategory::class;
        $this->assistanceTermClass = AssistanceTerm::class;
        $this->attributesClass = Attributes::class;
        $this->locationClass = Location::class;
        $this->locationCategoryClass = LocationCategory::class;
        $this->bookingClass = Booking::class;
        parent::__construct();
    }

    public function callAction($method, $parameters)
    {
        if (setting_item('assistance_disable')) {
            return redirect('/');
        }
        return parent::callAction($method, $parameters); // TODO: Change the autogenerated stub
    }

    public function manageAssistance(Request $request)
    {
        $this->checkPermission('assistance_view');
        $user_id = Auth::id();
        $list_assistance = $this->assistanceClass::where("author_id", $user_id)->orderBy('id', 'desc');
        $data = [
            'rows'        => $list_assistance->paginate(5),
            'breadcrumbs' => [
                [
                    'name' => __('Gerenciar Serviços'),
                    'url'  => route('assistance.vendor.index'),
                ],
                [
                    'name'  => __('Todos'),
                    'class' => 'active'
                ],
            ],
            'page_title'  => __("Gerenciar Serviços"),
        ];
        return view('Assistance::frontend.manageAssistance.index', $data);
    }

    public function recovery(Request $request)
    {
        $this->checkPermission('assistance_view');
        $user_id = Auth::id();
        $list_assistance = $this->assistanceClass::onlyTrashed()->where("author_id", $user_id)->orderBy('id', 'desc');
        $data = [
            'rows'        => $list_assistance->paginate(5),
            'recovery'           => 1,
            'breadcrumbs' => [
                [
                    'name' => __('Gerenciar Serviços'),
                    'url'  => route('assistance.vendor.index'),
                ],
                [
                    'name'  => __('Recuperação'),
                    'class' => 'active'
                ],
            ],
            'page_title'  => __("Recuperação Serviços"),
        ];
        return view('Assistance::frontend.manageAssistance.index', $data);
    }

    public function restore($id)
    {
        $this->checkPermission('assistance_delete');
        $user_id = Auth::id();
        $query = $this->assistanceClass::onlyTrashed()->where("author_id", $user_id)->where("id", $id)->first();
        if(!empty($query)){
            $query->restore();
        }
        return redirect(route('assistance.vendor.recovery'))->with('success', __('Restauração do serviço bem-sucedida!'));
    }

    public function createAssistance(Request $request)
    {
